// Función para formatear números a 2 decimales (solo para valores que parecen tiempos)
const formatearNumero = (valor) => {
  if (valor === null || valor === undefined) return '-';
  if (typeof valor === 'number') {
    // Redondear a 2 decimales si es un número
    return valor.toFixed(2);
  }
  // Si es string numérico (como las cuadras), mantener como string
  if (typeof valor === 'string' && !isNaN(parseFloat(valor)) && valor.includes('.')) {
    return valor;
  }
  return valor;
};


